#!/bin/bash
# Build ANGLE (GLES3-over-Metal) for visionOS from WebKit's visionOS-proven copy,
# and produce the standard-name shim RetroArch links against.
#
# Products (staged into vendor/RetroArch/pkg/apple/Frameworks/angle-xros/):
#   libANGLE-shared.dylib   - ANGLE with Metal backend (exports EGL_*/GL_* names,
#                             WebKit convention; Metal shader lib embedded)
#   libEGLGLES_shim.dylib   - 944 standard-name (egl*/gl*) tail-jump thunks
#                             forwarding into libANGLE-shared
#   include/                - EGL/GLES2/GLES3/KHR headers + OpenGLES/{ES2,ES3}
#                             shim mapping for RetroArch's IOS include paths
#
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${ANGLE_WORK:-$REPO/work/angle-build}"
STAGE="$REPO/vendor/RetroArch/pkg/apple/Frameworks/angle-xros"
XRSDK="$(xcrun --sdk xros --show-sdk-path)"
TGT=arm64-apple-xros26.0

mkdir -p "$WORK"
cd "$WORK"

# 1. Sparse-checkout just ANGLE + the WebKit config bits it needs (~250 MB).
if [ ! -d wk ]; then
    git clone --depth 1 --filter=blob:none --sparse https://github.com/WebKit/WebKit.git wk
    (cd wk && git sparse-checkout set Source/ThirdParty/ANGLE Configurations Tools/ccache)
fi
(cd wk && git rev-parse HEAD > "$WORK/webkit-pin.txt")

A="$WORK/wk/Source/ThirdParty/ANGLE"

# ANGLE's Apple pthread-key TLS is deletable by any other library in
# the process; a dead key silently swallows every store and ANGLE NULL-derefs
# its per-thread state (the visionOS content-reload SIGSEGV). Switch it to real
# thread_local. Idempotent, match-count asserted.
python3 "$REPO/scripts/angle-static-tls-patch.py" "$A"

BUILD="$WORK/build"
OBJ="$WORK/obj"

# 2. The build injects a VFS overlay generated by WebKit's full build; an empty
#    overlay satisfies clang for a standalone ANGLE build.
mkdir -p "$BUILD"
printf '{"version": 0, "roots": []}\n' > "$BUILD/availability-overlay.yaml"

# 3. Build. WK_USE_CCACHE=NO (the ccache wrapper breaks ScanDependencies),
#    ANGLE_ALLOWABLE_CLIENTS="" (drop the WebCore-only link restriction).
xcodebuild build -project "$A/ANGLE.xcodeproj" -target "ANGLE (dynamic)" \
    -configuration Release -sdk xros ARCHS=arm64 ONLY_ACTIVE_ARCH=YES \
    CODE_SIGNING_ALLOWED=NO XROS_DEPLOYMENT_TARGET=26.0 \
    WK_USE_CCACHE=NO ANGLE_ALLOWABLE_CLIENTS="" \
    SYMROOT="$BUILD" OBJROOT="$OBJ"

DYLIB="$BUILD/Release-xros/libANGLE-shared.dylib"
vtool -show-build "$DYLIB" | grep -q VISIONOS

# 4. Stage headers (+ OpenGLES/ mapping for RetroArch's IOS include ladder).
mkdir -p "$STAGE/include/OpenGLES/ES3" "$STAGE/include/OpenGLES/ES2"
for d in EGL GLES2 GLES3 KHR GLES; do
    [ -d "$A/include/$d" ] && cp -R "$A/include/$d" "$STAGE/include/"
done
printf '#include <GLES3/gl3.h>\n' > "$STAGE/include/OpenGLES/ES3/gl.h"
printf '#ifndef __gl2_h_\n#define __gl2_h_ 1\n#endif\n#include <GLES2/gl2ext.h>\n' \
    > "$STAGE/include/OpenGLES/ES3/glext.h"
printf '#include <GLES2/gl2.h>\n'    > "$STAGE/include/OpenGLES/ES2/gl.h"
printf '#include <GLES2/gl2ext.h>\n' > "$STAGE/include/OpenGLES/ES2/glext.h"

# 5. Stage the dylib under an @rpath id (app Frameworks dir is on the rpath).
cp "$DYLIB" "$STAGE/"
install_name_tool -id @rpath/libANGLE-shared.dylib "$STAGE/libANGLE-shared.dylib"

# 6. Generate the standard-name thunks (eglFoo -> EGL_Foo, glFoo -> GL_Foo);
#    pure arm64 tail-jumps, ABI-transparent for any signature.
nm -gU "$STAGE/libANGLE-shared.dylib" \
    | awk '$2=="T" && $3 ~ /^_(EGL|GL)_/ {sub(/^_/,"",$3); print $3}' > "$WORK/entrypoints.txt"
python3 - "$WORK/entrypoints.txt" "$WORK/thunks.s" <<'EOF'
import sys
out = [".text"]
for line in open(sys.argv[1]):
    n = line.strip()
    if n.startswith("EGL_"): alias = "egl" + n[4:]
    elif n.startswith("GL_"): alias = "gl" + n[3:]
    else: continue
    out.append(f".globl _{alias}\n.p2align 2\n_{alias}:\n   b _{n}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
EOF
clang -c -target "$TGT" -isysroot "$XRSDK" -o "$WORK/thunks.o" "$WORK/thunks.s"
clang -dynamiclib -target "$TGT" -isysroot "$XRSDK" \
    -install_name @rpath/libEGLGLES_shim.dylib \
    -o "$STAGE/libEGLGLES_shim.dylib" "$WORK/thunks.o" "$STAGE/libANGLE-shared.dylib"

echo "=== staged: $STAGE"
echo "shim exports: egl=$(nm -gU "$STAGE/libEGLGLES_shim.dylib" | grep -c ' T _egl') gl=$(nm -gU "$STAGE/libEGLGLES_shim.dylib" | grep -c ' T _gl')"
